# Assignment Operators
a = 4 - 2 # Assign 4- 2 to a
print(a)

b = 6

b += 3 
print(b)# Increment the value of b by 3 and then assign it to b

b -= 3 # Decrement the value of b by 3 and then assign it to b
print(b)

b *= 3 # Multiply the value of b by 3 and then assign it to b
print(b)

b /= 3 # Divide the value of b by 3 and then assign it to b
print(b)

b %= 3 # Assign the remainder of b divided by 3 to b
print(b)
