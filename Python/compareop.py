# Comparison Operators

d = 5==5 # Check if 5 is equal to 5
print(d)

d = 5!=5 # Check if 5 is not equal to 5
print(d)

d = 5>5 # Check if 5 is greater than 5
print(d)

d = 5<5 # Check if 5 is less than 5
print(d)

d = 5>=5 # Check if 5 is greater than or equal to 5
print(d)

d = 5<=5 # Check if 5 is less than or equal to 5
print(d)

d = 5 is 5 # Check if 5 is the same object as 5
print(d)

d = 5 is not 5 # Check if 5 is not the same object as 5
print(d)

d = 5 in [1,2,3,4,5] # Check if 5 is in the list
print(d)

d = 5 not in [1,2,3,4,5] # Check if 5 is not in the list
print(d)

d = 5 is not 6 # Check if 5 is not the same object as 6 
print(d)

d = 5 is 6 # Check if 5 is the same object as 6
print(d)
